#@title Cell 8 - How much is there? Absolute abundance of the redox enzymes
PRESENT = gpos
OUTDIR = GDIR
GROUPS = [MIT, ENDO]
LEVELS = pd.DataFrame({MIT: Lp.xs(MIT, level=1, axis=1).mean(axis=1),
                       ENDO: Lp.xs(ENDO, level=1, axis=1).mean(axis=1)})
# The screens above measure CHANGE. A programme can shift a long way and still be a minor part
# of the cell, and a gene can be hugely abundant and barely move. This cell reports amount.
CLASSES = {
    "H2O2 removal": "Jafrac1 Jafrac2 Prx3 Prx5 Prx2540-1 Prx2540-2 PHGPx Cat Srx",
    "thioredoxin system (regenerates peroxiredoxins)": "Trxr-1 Trxr-2 Trx-2 TrxT dhd",
    "superoxide dismutases": "Sod1 Sod2 Sod3",
    "glutathione supply": "Gclc Gclm Gss1 Gss2 Gr1 Grx1 Grx1t GILT1",
    "NADPH supply": "Zw Pgd Men Men-b Idh Idh3a Tkt Taldo Nmdmc",
    "H2O2 sources": "Ero1L Duox Nox Aox1 Pxd Pxt Uro Mav Cyp4e3",
}
CLASSES = {k: [r for g in v.split() if (r := resolve(g, PRESENT)) and r in LEVELS.index]
           for k, v in CLASSES.items()}
pct_level = LEVELS.mean(axis=1).rank(pct=True)
rows = []
for cls, gs in CLASSES.items():
    for g in gs:
        r = {"gene": g, "class": cls}
        for grp in GROUPS:
            r[grp] = LEVELS[grp].loc[g] if g in LEVELS.index else np.nan
        r["abundance_pct"] = pct_level.get(g, np.nan)
        rows.append(r)
ab = pd.DataFrame(rows).dropna(subset=GROUPS, how="all").set_index("gene")
ab["change"] = ab[GROUPS[-1]] - ab[GROUPS[0]]
display(ab.sort_values(["class", GROUPS[0]], ascending=[True, False]).round(2))
print("Values are log2 CPM. abundance_pct is the gene's rank by expression among all "
      f"{len(pct_level):,} expressed genes (1.00 = highest).")

print("\nTotal capacity per class, as CPM summed across its genes (not logs, so these are comparable amounts):")
tot = pd.DataFrame({grp: ab.groupby("class")[grp].apply(lambda s: (2 ** s.dropna()).sum()) for grp in GROUPS})
tot["fold_change"] = tot[GROUPS[-1]] / tot[GROUPS[0]]
display(tot.round(1))
rm, sr = "H2O2 removal", "H2O2 sources"
if rm in tot.index and sr in tot.index:
    for grp in GROUPS:
        print(f"   {grp}: H2O2-removing transcripts are {tot.loc[rm, grp] / max(tot.loc[sr, grp], 1e-9):.0f}x "
              f"the H2O2-producing ones")

fig, ax = plt.subplots(figsize=(7.5, 0.26 * len(ab) + 1.6))
ab2 = ab.sort_values(["class", GROUPS[0]])
y = np.arange(len(ab2))
for k, grp in enumerate(GROUPS):
    ax.barh(y + (k - (len(GROUPS) - 1) / 2) * 0.38, 2 ** ab2[grp].to_numpy(), height=0.36, label=grp)
ax.set_yticks(y); ax.set_yticklabels([f"{g}  ({c.split(' (')[0]})" for g, c in zip(ab2.index, ab2["class"])], fontsize=7)
ax.set_xscale("log"); ax.set_xlabel("CPM (log scale)"); ax.invert_yaxis(); ax.legend(fontsize=8)
ax.set_title("How much of each redox enzyme is present", loc="left", fontsize=10)
plt.tight_layout(); plt.savefig(os.path.join(OUTDIR, "chart_abundance.png"), dpi=150); plt.show()
ab.to_csv(os.path.join(OUTDIR, "abundance.csv")); tot.to_csv(os.path.join(OUTDIR, "abundance_totals.csv"))
print("\nTranscript amount is not protein amount and not enzymatic flux. Peroxiredoxins are consumed per molecule of "
      "H2O2 and must be regenerated by thioredoxin and NADPH, while Ero1 turns over catalytically, so an abundant "
      "sink does not automatically outweigh a scarce source.")
